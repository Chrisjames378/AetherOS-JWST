import React, { useState } from 'react';
import { Download, FileText, CheckCircle2 } from 'lucide-react';

interface FITSParams {
  target: string;
  instrument: string;
  filter: string;
  exposureSec: number;
  observer: string;
  date: string;
}

function pad80(str: string): string {
  return str.padEnd(80, ' ').slice(0, 80);
}

function formatFITSString(key: string, val: string, comment = ''): string {
  const quoteVal = `'${val.replace(/'/g, '').padEnd(8, ' ')}'`;
  const line = `${key.padEnd(8, ' ')}= ${quoteVal.padEnd(20, ' ')} / ${comment}`;
  return pad80(line);
}

function formatFITSNumber(key: string, val: number, comment = ''): string {
  const line = `${key.padEnd(8, ' ')}= ${val.toString().padStart(20, ' ')} / ${comment}`;
  return pad80(line);
}

function formatFITSBool(key: string, val: boolean, comment = ''): string {
  const line = `${key.padEnd(8, ' ')}= ${val ? 'T'.padStart(20, ' ') : 'F'.padStart(20, ' ')} / ${comment}`;
  return pad80(line);
}

export function generateFITSFile(params: FITSParams): { blob: Blob; filename: string } {
  const cards: string[] = [
    formatFITSBool('SIMPLE', true, 'file conforms to FITS standard'),
    formatFITSNumber('BITPIX', -32, 'IEEE 754 single precision float'),
    formatFITSNumber('NAXIS', 2, 'number of data axes (2D image array)'),
    formatFITSNumber('NAXIS1', 128, 'pixels on axis 1 (fastest)'),
    formatFITSNumber('NAXIS2', 128, 'pixels on axis 2'),
    formatFITSBool('EXTEND', true, 'FITS extensions may be present'),
    formatFITSString('TELESCOP', 'JWST', 'James Webb Space Telescope'),
    formatFITSString('INSTRUME', params.instrument, 'active focal plane instrument'),
    formatFITSString('FILTER', params.filter, 'optical element bandpass'),
    formatFITSString('TARGNAME', params.target, 'astronomical target name'),
    formatFITSNumber('EXPTIME', params.exposureSec, 'exposure duration in seconds'),
    formatFITSString('OBSERVER', params.observer, 'observer or consortium'),
    formatFITSString('DATE-OBS', params.date, 'UTC observation date'),
    formatFITSString('ORIGIN', 'AetherOS', 'JWST simulation & flight bench'),
    formatFITSNumber('BZERO', 0.0, 'physical = BZERO + BSCALE * array_value'),
    formatFITSNumber('BSCALE', 1.0, 'physical = BZERO + BSCALE * array_value'),
    pad80('COMMENT   Simulated synthetic science stamp generated by AetherOS.'),
    pad80('END'),
  ];

  // Header must be an exact multiple of 2880 bytes (36 lines of 80 characters per block)
  const headerLinesCount = Math.ceil(cards.length / 36) * 36;
  while (cards.length < headerLinesCount) {
    cards.push(pad80(''));
  }

  const headerStr = cards.join('');
  const headerBytes = new Uint8Array(headerStr.length);
  for (let i = 0; i < headerStr.length; i++) {
    headerBytes[i] = headerStr.charCodeAt(i);
  }

  // 128 x 128 float32 image array (Big-Endian)
  const width = 128;
  const height = 128;
  const pixelCount = width * height;
  const dataBytes = new Uint8Array(pixelCount * 4);
  const dataView = new DataView(dataBytes.buffer);

  // Generate synthetic point-spread function with hexagonal JWST diffraction spikes
  const cx = width / 2;
  const cy = height / 2;

  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const idx = (y * width + x) * 4;
      const dx = x - cx;
      const dy = y - cy;
      const dist = Math.hypot(dx, dy);

      // Central Airy core
      let val = Math.exp(-(dist * dist) / 18.0) * 8500.0;

      // Hexagonal 6-spike diffraction pattern (60° increments)
      for (let s = 0; s < 3; s++) {
        const angle = (s * Math.PI) / 3;
        const perpDist = Math.abs(dx * Math.sin(angle) - dy * Math.cos(angle));
        if (perpDist < 1.2 && dist > 2) {
          val += (1200.0 / (dist + 4)) * Math.exp(-perpDist * 1.5);
        }
      }

      // Background detector noise
      val += (Math.sin(x * 12.3 + y * 7.7) + Math.cos(x * 5.1 - y * 9.2)) * 8.5;

      dataView.setFloat32(idx, val, false); // false = Big-Endian
    }
  }

  // Data array padding to multiple of 2880
  const dataRemainder = dataBytes.byteLength % 2880;
  const paddingBytesCount = dataRemainder === 0 ? 0 : 2880 - dataRemainder;
  const paddingBytes = new Uint8Array(paddingBytesCount);

  const combinedBlob = new Blob([headerBytes, dataBytes, paddingBytes], {
    type: 'application/fits',
  });

  const sanitizedTarget = params.target.toLowerCase().replace(/[^a-z0-9_-]/g, '_');
  const filename = `jwst_${sanitizedTarget}_${params.filter.toLowerCase()}_stamp.fits`;

  return { blob: combinedBlob, filename };
}

export const FITSTool: React.FC = () => {
  const [target, setTarget] = useState<string>('WASP-96b');
  const [instrument, setInstrument] = useState<string>('NIRCam');
  const [filter, setFilter] = useState<string>('F444W');
  const [exposureSec, setExposureSec] = useState<number>(2400);
  const [observer, setObserver] = useState<string>('AetherOS Team');
  const [downloadSuccess, setDownloadSuccess] = useState<boolean>(false);

  const handleDownload = () => {
    const today = new Date().toISOString().slice(0, 10);
    const { blob, filename } = generateFITSFile({
      target,
      instrument,
      filter,
      exposureSec,
      observer,
      date: today,
    });

    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);

    setDownloadSuccess(true);
    setTimeout(() => setDownloadSuccess(false), 4000);
  };

  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div>
          <h2 className="text-xl font-semibold tracking-tight text-fg flex items-center gap-2">
            <FileText className="w-5 h-5 text-flare" />
            FITS science data exporter
          </h2>
          <p className="mt-1 text-sm text-pretty text-muted">
            Generates standard 32-bit big-endian IEEE-754 floating-point 128×128 pixel FITS arrays with authentic 2880-byte header blocks.
          </p>
        </div>
        <button
          type="button"
          onClick={handleDownload}
          className="min-h-10 bg-flare hover:bg-flare/90 text-flare-ink px-4 py-2 text-sm font-semibold rounded transition-colors flex items-center gap-1.5 shadow-md"
        >
          {downloadSuccess ? (
            <>
              <CheckCircle2 className="w-4 h-4" />
              Downloaded FITS!
            </>
          ) : (
            <>
              <Download className="w-4 h-4" />
              Download FITS file
            </>
          )}
        </button>
      </div>

      <div className="grid gap-3 sm:grid-cols-2">
        <div className="space-y-1">
          <label className="font-mono text-xs text-muted block">ASTRONOMICAL TARGET</label>
          <input
            type="text"
            value={target}
            onChange={(e) => setTarget(e.target.value)}
            className="w-full min-h-10 border border-line bg-bg px-3 font-mono text-sm text-fg rounded focus:outline-none focus:border-flare"
          />
        </div>

        <div className="space-y-1">
          <label className="font-mono text-xs text-muted block">SCIENCE INSTRUMENT</label>
          <select
            value={instrument}
            onChange={(e) => setInstrument(e.target.value)}
            className="w-full min-h-10 border border-line bg-bg px-3 font-mono text-sm text-fg rounded focus:outline-none focus:border-flare"
          >
            <option value="NIRCam">NIRCam (Near-Infrared Camera)</option>
            <option value="MIRI">MIRI (Mid-Infrared Instrument)</option>
            <option value="NIRSpec">NIRSpec (Near-Infrared Spectrograph)</option>
            <option value="NIRISS">NIRISS (Wide Field Slitless)</option>
          </select>
        </div>

        <div className="space-y-1">
          <label className="font-mono text-xs text-muted block">OPTICAL FILTER</label>
          <input
            type="text"
            value={filter}
            onChange={(e) => setFilter(e.target.value)}
            className="w-full min-h-10 border border-line bg-bg px-3 font-mono text-sm text-fg rounded focus:outline-none focus:border-flare"
          />
        </div>

        <div className="space-y-1">
          <label className="font-mono text-xs text-muted block">EXPOSURE DURATION (SEC)</label>
          <input
            type="number"
            min="10"
            max="100000"
            step="100"
            value={exposureSec}
            onChange={(e) => setExposureSec(parseInt(e.target.value) || 0)}
            className="w-full min-h-10 border border-line bg-bg px-3 font-mono text-sm text-fg rounded focus:outline-none focus:border-flare"
          />
        </div>
      </div>

      <div className="space-y-1">
        <label className="font-mono text-xs text-muted block">PRINCIPAL OBSERVER / CONSORTIUM</label>
        <input
          type="text"
          value={observer}
          onChange={(e) => setObserver(e.target.value)}
          className="w-full min-h-10 border border-line bg-bg px-3 text-sm text-fg rounded focus:outline-none focus:border-flare"
        />
      </div>

      <div className="border border-line bg-surface p-3 rounded font-mono text-xs text-muted space-y-1">
        <p className="text-fg font-semibold">HEADER PREVIEW (2880-BYTE BLOCK):</p>
        <p className="text-[11px] text-muted overflow-x-auto whitespace-pre font-mono">
{`SIMPLE  =                    T / file conforms to FITS standard
BITPIX  =                  -32 / IEEE 754 single precision float
NAXIS   =                    2 / number of data axes
NAXIS1  =                  128 / pixels on axis 1
NAXIS2  =                  128 / pixels on axis 2
TELESCOP= 'JWST    '           / James Webb Space Telescope
INSTRUME= '${instrument.padEnd(8, ' ')}'           / active focal plane instrument
FILTER  = '${filter.padEnd(8, ' ')}'           / optical bandpass
TARGNAME= '${target.padEnd(8, ' ')}'           / astronomical target`}
        </p>
      </div>
    </div>
  );
};
